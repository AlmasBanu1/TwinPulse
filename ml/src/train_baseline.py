
from pathlib import Path
import json

import joblib
import numpy as np
import pandas as pd

from sklearn.compose import ColumnTransformer
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    average_precision_score,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
    roc_auc_score,
)
from sklearn.model_selection import StratifiedKFold, cross_val_predict
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler


ROOT = Path(__file__).resolve().parents[2]

INPUT = ROOT / "data" / "processed" / "sharee_model_table.csv"
OUTPUT_DIR = ROOT / "data" / "processed" / "baseline"

PREDICTIONS_FILE = OUTPUT_DIR / "oof_predictions.csv"
METRICS_FILE = OUTPUT_DIR / "baseline_metrics.json"
MODEL_FILE = OUTPUT_DIR / "sharee_logistic_pipeline.joblib"

# Intentionally exclude record_id and vascular_event.
NUMERIC_FEATURES = [
    "age",
    "bmi",
    "sbp",
    "dbp",
    "imt_max",
    "lvmi",
    "ef",
]

CATEGORICAL_FEATURES = [
    "gender",
    "smoker",
]

TARGET = "target_event"


def main():
    if not INPUT.exists():
        raise FileNotFoundError(
            f"Modeling table not found: {INPUT}"
        )

    # Preserve patient IDs as strings, including leading zeros.
    df = pd.read_csv(
        INPUT,
        dtype={"record_id": "string"},
    )

    required = set(
        NUMERIC_FEATURES + CATEGORICAL_FEATURES + [TARGET]
    )
    missing = required - set(df.columns)

    if missing:
        raise ValueError(
            f"Missing required columns: {sorted(missing)}"
        )

    if "record_id" not in df.columns:
        raise ValueError("Missing required column: record_id")

    if df[TARGET].isna().any():
        raise ValueError("Target contains missing values.")

    if set(df[TARGET].unique()) != {0, 1}:
        raise ValueError(
            "Expected a binary target containing 0 and 1."
        )

    if df["record_id"].isna().any():
        raise ValueError("Patient IDs contain missing values.")

    if df["record_id"].duplicated().any():
        raise ValueError("Duplicate patient IDs detected.")

    X = df[NUMERIC_FEATURES + CATEGORICAL_FEATURES].copy()
    y = df[TARGET].astype(int)

    # Numeric preprocessing.
    numeric_pipeline = Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler", StandardScaler()),
    ])

    # Categorical preprocessing.
    categorical_pipeline = Pipeline([
        ("imputer", SimpleImputer(strategy="most_frequent")),
        ("encoder", OneHotEncoder(handle_unknown="ignore")),
    ])

    preprocessing = ColumnTransformer([
        (
            "numeric",
            numeric_pipeline,
            NUMERIC_FEATURES,
        ),
        (
            "categorical",
            categorical_pipeline,
            CATEGORICAL_FEATURES,
        ),
    ])

    # Complete preprocessing + classifier pipeline.
    model = Pipeline([
        ("preprocessing", preprocessing),
        (
            "classifier",
            LogisticRegression(
                class_weight="balanced",
                max_iter=2000,
                random_state=42,
            ),
        ),
    ])

    cv = StratifiedKFold(
        n_splits=5,
        shuffle=True,
        random_state=42,
    )

    # Each patient's evaluation prediction is generated by a model
    # that did not train on that patient.
    #
    # Imputation, scaling, and encoding are fitted independently
    # inside each training fold.
    probabilities = cross_val_predict(
        model,
        X,
        y,
        cv=cv,
        method="predict_proba",
        n_jobs=1,
    )[:, 1]

    # Default threshold for exploration only.
    # It is not a clinically selected threshold.
    predictions = (
        probabilities >= 0.5
    ).astype(int)

    tn, fp, fn, tp = confusion_matrix(
        y,
        predictions,
        labels=[0, 1],
    ).ravel()

    metrics = {
        "model": "LogisticRegression",
        "evaluation": (
            "5-fold stratified out-of-fold predictions"
        ),
        "n_patients": int(len(df)),
        "n_positive": int(y.sum()),
        "n_negative": int((y == 0).sum()),
        "features_numeric": NUMERIC_FEATURES,
        "features_categorical": CATEGORICAL_FEATURES,
        "threshold": 0.5,
        "class_weight": "balanced",
        "precision": float(
            precision_score(
                y,
                predictions,
                zero_division=0,
            )
        ),
        "recall_sensitivity": float(
            recall_score(
                y,
                predictions,
                zero_division=0,
            )
        ),
        "f1": float(
            f1_score(
                y,
                predictions,
                zero_division=0,
            )
        ),
        "roc_auc": float(
            roc_auc_score(y, probabilities)
        ),
        "average_precision": float(
            average_precision_score(y, probabilities)
        ),
        "confusion_matrix": {
            "true_negative": int(tn),
            "false_positive": int(fp),
            "false_negative": int(fn),
            "true_positive": int(tp),
        },
        "limitations": [
            "Only 17 positive outcomes are available.",
            (
                "This is exploratory internal evaluation, "
                "not external validation."
            ),
            (
                "Predicted probabilities are not established "
                "clinical risk estimates."
            ),
            (
                "The 0.5 threshold is a default, "
                "not a clinically selected threshold."
            ),
        ],
    }

    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    # Save a separate final pipeline for dashboard inference.
    #
    # IMPORTANT:
    # This model is fitted on the entire dataset for demo use.
    # It is NOT used to calculate the cross-validation metrics.
    final_model = model.fit(X, y)

    joblib.dump(
        final_model,
        MODEL_FILE,
    )

    # Save out-of-fold evaluation predictions.
    predictions_df = pd.DataFrame({
        "record_id": df["record_id"],
        "actual_target": y,
        "predicted_probability": probabilities,
        "predicted_target_at_0_5": predictions,
    })

    predictions_df.to_csv(
        PREDICTIONS_FILE,
        index=False,
    )

    # Save evaluation metrics.
    with METRICS_FILE.open(
        "w",
        encoding="utf-8",
    ) as f:
        json.dump(
            metrics,
            f,
            indent=2,
        )

    print("=" * 60)
    print("TWINPULSE - BASELINE MODEL")
    print("=" * 60)

    print("Model: Logistic Regression")
    print(
        "Evaluation: 5-fold stratified out-of-fold predictions"
    )
    print(f"Patients: {len(df)}")
    print(f"Positive outcomes: {int(y.sum())}")
    print(f"Negative outcomes: {int((y == 0).sum())}")

    print("\nMetrics (exploratory):")

    for key in [
        "precision",
        "recall_sensitivity",
        "f1",
        "roc_auc",
        "average_precision",
    ]:
        print(f"{key}: {metrics[key]:.4f}")

    print("\nConfusion matrix:")
    print("                 Predicted 0   Predicted 1")
    print(f"Actual 0         {tn:11d}   {fp:11d}")
    print(f"Actual 1         {fn:11d}   {tp:11d}")

    print("\nSaved out-of-fold predictions to:")
    print(PREDICTIONS_FILE)

    print("\nSaved evaluation metrics to:")
    print(METRICS_FILE)

    print("\nSaved fitted model for demo inference to:")
    print(MODEL_FILE)

    print(
        "\nWARNING: This small-cohort experiment is not a "
        "clinically validated prediction model."
    )


if __name__ == "__main__":
    main()
